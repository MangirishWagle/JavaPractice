package JavaLoops;

public class ForEachLoopDemo {

	public static void main(String[] args) {
		int[] numbers = {10, 20, 30, 40, 50};
		
		for (int number: numbers) {
			System.out.println("Iteration number: " + number);
		}
		
		/*
		 * 
		 *	numbers --> Declaring an array of numbers from position 0 to 4 i.e. iteration 1 to 5
		 *  int number --> temporary variable that holds each element of an array
		 * 
		 * 
		 * */

	}

}
