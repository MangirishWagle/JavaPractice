package JavaDataTypes;

public class PrimitiveDataTypes {

	public static void main(String[] args) {
		byte smallNumber = 100;
		char firstLetterOfMyName = 'M';
		float piValue = 3.14f;
		double largeDecimal = 12345.6789;
		boolean isJavaFun = true;
		
		System.out.println("byte is a smallNumber whose value is: " + smallNumber);
		System.out.println("char is a single letter whose value is: " + firstLetterOfMyName);
		System.out.println("float is a decimal number. Example is a pi whose value is: " + piValue);
		System.out.println("double is a large decimal whose value is: " + largeDecimal);
		System.out.println("boolean is a binary data type, whose current value is: " + isJavaFun);
		
	}

}


